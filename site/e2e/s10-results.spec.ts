import { test, expect } from './support/fixtures'
import { signInAs, restAsPage, expectNoHorizontalScroll } from './support/browser'
import { SEASON_ID, withDatabase } from './support/database'

test('S10 submit, edit, dispute, agree, settle and reopen', async ({ page }) => {
  const { game, ids } = await withDatabase(async db => {
    await db.query("update public.seasons set capacity=8,games_each=2,maps=array['Autumn','Winter'],started_at=now(),lists_lock_at=now()-interval '1 day' where id=$1", [SEASON_ID])
    const ids: string[] = []
    for (let i = 0; i < 4; i++) {
      const p = await db.query<{ id: string }>('insert into public.people(display_name,discord_id) values ($1,$2) returning id', [['Delaney', 'Blair', 'Casey', 'Devon'][i], i === 0 ? '100000000000000002' : null])
      ids.push(p.rows[0]!.id)
      await db.query("insert into public.roster(season_id,person_id,list,position,player_number) values ($1,$2,'league',$3,$3)", [SEASON_ID, ids[i], i + 1])
    }
    const g = await db.query<{ id: string }>('insert into public.games(season_id,game_no,map_index) values ($1,1,0) returning id', [SEASON_ID])
    const game = g.rows[0]!.id
    for (let i = 0; i < 4; i++) await db.query('insert into public.game_seats(game_id,seat,person_id,faction) values ($1,$2,$3,$4)', [game, i + 1, ids[i], ['cats', 'birds', 'otters', 'WA'][i]])
    return { game, ids }
  })
  await signInAs(page, 'player')
  await page.goto('/game/1')
  await page.getByRole('checkbox', { name: 'Delaney' }).check()
  await page.getByRole('button', { name: 'Submit', exact: true }).click()
  await expect(page.getByText('Won by Delaney', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Edit result' }).click()
  await page.getByRole('checkbox', { name: 'Blair' }).check()
  await page.getByRole('button', { name: 'Submit', exact: true }).click()
  await expect(page.getByText('Won by Delaney, Blair', { exact: true })).toBeVisible()
  await withDatabase(db => db.query('insert into public.submissions(game_id,person_id,winners) values ($1,$2,$3)', [game, ids[1], [ids[1]]]))
  await page.reload()
  await expect(page.getByRole('region', { name: 'Result' })).toContainText('The admin will decide.')
  await expect(page.getByText(/Won by/)).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Result' })).not.toContainText('Blair')
  await page.getByRole('button', { name: 'Edit result' }).click()
  await page.getByRole('checkbox', { name: 'Delaney' }).uncheck()
  await page.getByRole('button', { name: 'Submit', exact: true }).click()
  await expect(page.getByText('Won by Blair', { exact: true })).toBeVisible()
  await expectNoHorizontalScroll(page)
  await page.evaluate(() => localStorage.clear())
  await signInAs(page, 'admin')
  expect((await restAsPage(page, 'rpc/settle_game', { p_game_id: game, p_winners: [ids[0]] })).status).toBe(204)
  await page.evaluate(() => localStorage.clear())
  await signInAs(page, 'player')
  await page.goto('/game/1')
  await expect(page.getByText('Settled by admin')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Edit result' })).toHaveCount(0)
  await expect(page.getByRole('checkbox')).toHaveCount(0)
  await page.evaluate(() => localStorage.clear())
  await signInAs(page, 'admin')
  expect((await restAsPage(page, 'rpc/reopen_game', { p_game_id: game })).status).toBe(204)
  await page.evaluate(() => localStorage.clear())
  await signInAs(page, 'player')
  await page.goto('/game/1')
  await expect(page.getByRole('button', { name: 'Edit result' })).toBeVisible()
  await page.evaluate(() => localStorage.clear())
  await signInAs(page, 'viewer')
  await page.goto('/game/1')
  await expect(page.getByText('Won by Blair', { exact: true })).toBeVisible()
  await expect(page.getByRole('checkbox')).toHaveCount(0)
  await withDatabase(db => db.query("insert into public.roster(season_id,person_id,list,position) select $1,id,'waitlist',1 from public.people where discord_id='100000000000000014'", [SEASON_ID]))
  await page.reload()
  await expect(page.getByText('Won by Blair', { exact: true })).toBeVisible()
  await expect(page.getByRole('checkbox')).toHaveCount(0)
  expect((await restAsPage(page, 'rpc/submit_result', { p_game_id: game, p_winners: [ids[0]] })).status).toBe(403)
})
